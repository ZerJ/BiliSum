from __future__ import annotations

import os
import re
import tempfile
import time
from pathlib import Path
from threading import RLock

from video_sum_service.context import settings_manager

MAX_COOKIE_BYTES = 1024 * 1024
_write_lock = RLock()
_LOGIN_NAMES = {"sessionid", "sessionid_ss", "sid_tt"}
_COOKIE_NAME = re.compile(r"^[!#$%&'*+.^_`|~0-9A-Za-z-]+$")


def domain_matches(domain: str, suffix: str) -> bool:
    host = domain.removeprefix("#HttpOnly_").lstrip(".").lower()
    return host == suffix or host.endswith("." + suffix)


def _netscape_rows(text: str) -> list[list[str]]:
    rows = []
    for line in text.lstrip("\ufeff").splitlines():
        if not line.strip() or (line.startswith("#") and not line.startswith("#HttpOnly_")):
            continue
        fields = line.split("\t")
        if len(fields) != 7:
            raise ValueError("Cookies 文件格式无效，请导出 Netscape cookies.txt，或粘贴 Cookie 请求头。")
        domain, subdomains, path, secure, expires, name, value = fields
        if (
            not domain or subdomains not in {"TRUE", "FALSE"}
            or not path.startswith("/") or secure not in {"TRUE", "FALSE"}
            or not expires.isdigit() or not _COOKIE_NAME.fullmatch(name)
            or any(ord(char) < 32 or ord(char) == 127 for char in value)
        ):
            raise ValueError("Cookies 文件中包含无效字段，请重新导出。")
        rows.append(fields)
    return rows


def _cookie_key(fields: list[str]) -> tuple[str, str, str]:
    return (fields[0].removeprefix("#HttpOnly_").lower(), fields[2], fields[5])


def write_site_cookies(rows: list[list[str]], suffix: str) -> str:
    """Replace one site's cookies while keeping login cookies for other sites."""
    settings = settings_manager.current
    target = Path(settings.data_dir) / "cookies" / "sites.txt"
    with _write_lock:
        existing: dict[tuple[str, str, str], list[str]] = {}
        sources = [target.parent / "bilibili.txt", target]
        if settings.ytdlp_cookies_file:
            sources.append(Path(settings.ytdlp_cookies_file))
        for source in dict.fromkeys(sources):
            if not source.is_file():
                continue
            if source.stat().st_size > MAX_COOKIE_BYTES:
                raise ValueError("已有 Cookies 文件超过 1 MB，请检查 Cookies 设置。")
            for fields in _netscape_rows(source.read_text(encoding="utf-8")):
                if any(domain_matches(fields[0], site) for site in ("bilibili.com", "douyin.com", "iesdouyin.com")):
                    if not domain_matches(fields[0], suffix):
                        existing[_cookie_key(fields)] = fields
        for fields in rows:
            existing[_cookie_key(fields)] = fields
        target.parent.mkdir(parents=True, exist_ok=True)
        content = "\n".join([
            "# Netscape HTTP Cookie File",
            "# Generated by BiliSum. Contains merged site login cookies.",
            *["\t".join(fields) for _, fields in sorted(existing.items())], "",
        ])
        temp_path = None
        try:
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=target.parent, delete=False) as temp:
                temp_path = Path(temp.name)
                temp.write(content)
            os.chmod(temp_path, 0o600)
            os.replace(temp_path, target)
        finally:
            if temp_path is not None:
                temp_path.unlink(missing_ok=True)
    return str(target)


def import_douyin_cookies(text: str) -> dict[str, object]:
    if len(text.encode("utf-8")) > MAX_COOKIE_BYTES:
        raise ValueError("Cookies 内容不能超过 1 MB。")
    clean = text.lstrip("\ufeff").strip("\r\n")
    if not clean.strip():
        raise ValueError("请上传 cookies.txt 或粘贴抖音 Cookie。")
    if "\t" in clean or clean.startswith("#"):
        rows = _netscape_rows(clean)
    else:
        clean = re.sub(r"^cookie:\s*", "", clean.strip(), flags=re.IGNORECASE)
        rows = []
        for item in clean.split(";"):
            if not item.strip():
                continue
            name, separator, value = item.strip().partition("=")
            if not separator or not _COOKIE_NAME.fullmatch(name) or any(ord(c) < 32 or ord(c) == 127 for c in value):
                raise ValueError("Cookie 请求头格式无效，应为 name=value; name2=value2。")
            rows.append([".douyin.com", "TRUE", "/", "TRUE", "0", name, value])
    now = time.time()
    cookies = [fields for fields in rows if domain_matches(fields[0], "douyin.com")
               and (int(fields[4]) == 0 or int(fields[4]) > now) and fields[6]]
    if not any(fields[5] in _LOGIN_NAMES for fields in cookies):
        raise ValueError("未找到有效抖音登录态（sessionid / sessionid_ss / sid_tt），请登录后重新导出。")
    cookies = list({_cookie_key(fields): fields for fields in cookies}.values())
    return {"cookiesFile": write_site_cookies(cookies, "douyin.com"), "cookieCount": len(cookies)}
